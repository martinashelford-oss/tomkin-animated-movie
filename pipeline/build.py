"""Compose Veo prompts and write the production documents."""
from __future__ import annotations

import csv
import json
from pathlib import Path

from .project import ROOT, Project, Shot, fmt_tc

PROMPTS_DIR = ROOT / "prompts"
DOCS_DIR = ROOT / "docs" / "generated"


def _clean(s: str) -> str:
    return " ".join(str(s).split())


def _speaker(p: Project, who: str) -> str:
    return p.characters[who]["name"]


def _dialogue_block(p: Project, lines) -> str:
    out = []
    for d in lines:
        c = p.characters[d.who]
        delivery = f", {d.delivery}" if d.delivery else ""
        out.append(f'{c["name"]} ({_clean(c["voice"])}{delivery}) says: "{d.spoken}"')
    return " ".join(out)


def _cast_block(p: Project, shot: Shot) -> str:
    parts = [_clean(p.characters[c]["look"]) for c in shot.characters]
    parts += [_clean(p.props[k]["look"]) for k in shot.props]
    return "; ".join(parts)


def reference_keys(p: Project, shot: Shot) -> list[str]:
    """Up to N reference-image keys (characters first, then props)."""
    if shot.refs is not None:
        return shot.refs
    n = p.config["veo"]["max_reference_images"]
    keys = [c for c in shot.characters if c not in ("dolphins",)] + list(shot.props)
    return keys[:n]


def base_prompt(p: Project, shot: Shot) -> str:
    loc = p.locations[shot.location]
    lines = [d for d in shot.dialogue if not d.ext]
    parts = [
        _clean(p.style["style"]) + ".",
        f"Setting: {_clean(loc['description'])}. Lighting: {_clean(loc['lighting'])}.",
    ]
    cast = _cast_block(p, shot)
    if cast:
        parts.append(f"In the shot: {cast}.")
    parts.append(f"Camera: {_clean(shot.camera)}.")
    parts.append(f"Action: {_clean(shot.action)}")
    if lines:
        parts.append("Dialogue: " + _dialogue_block(p, lines))
    else:
        parts.append("No dialogue.")
    sfx = ", ".join(shot.sfx) if shot.sfx else ""
    parts.append(f"Sound effects: {sfx}{', ' if sfx else ''}ambience of {_clean(loc['ambience'])}.")
    parts.append(_clean(p.style["audio_rule"]))
    return "\n".join(parts)


def ext_prompt(p: Project, shot: Shot) -> str | None:
    if not shot.extended:
        return None
    lines = [d for d in shot.dialogue if d.ext]
    names = ", ".join(_speaker(p, c) for c in shot.characters) or "the scene"
    parts = [
        "Continue this exact shot seamlessly: same characters, same designs, same "
        f"setting, same lighting and same 3D animated style ({names}).",
        f"Action: {_clean(shot.action_ext)}",
    ]
    if lines:
        parts.append("Dialogue: " + _dialogue_block(p, lines))
    else:
        parts.append("No dialogue.")
    if shot.sfx:
        parts.append("Sound effects continue: " + ", ".join(shot.sfx) + ".")
    parts.append(_clean(p.style["audio_rule"]))
    return "\n".join(parts)


def shot_record(p: Project, shot: Shot) -> dict:
    cue = p.cue_for(shot)
    return {
        "id": shot.id,
        "key": shot.key,
        "chapter": shot.chapter,
        "timecode_in": fmt_tc(shot.start),
        "timecode_out": fmt_tc(shot.start + shot.duration),
        "duration": shot.duration,
        "generate_seconds": p.gen_seconds(shot),
        "extended": shot.extended,
        "trim_in": shot.trim_in,
        "location": shot.location,
        "characters": shot.characters,
        "reference_images": [f"bible/refs/{k}.png" for k in reference_keys(p, shot)],
        "base_prompt": base_prompt(p, shot),
        "extension_prompt": ext_prompt(p, shot),
        "negative_prompt": _clean(p.style["negative_prompt"]),
        "music_cue": cue["id"] if cue else None,
        "overlay": shot.overlay,
    }


def cost_table(p: Project, takes: float = 1.0) -> list[tuple[str, str, float, float]]:
    gen = sum(p.gen_seconds(s) for s in p.shots)
    rows = []
    for tier, res_prices in p.config["veo"]["price_per_second"].items():
        for res, price in res_prices.items():
            rows.append((tier, res, gen * price, gen * price * takes))
    return rows


def write_all(p: Project) -> None:
    PROMPTS_DIR.mkdir(exist_ok=True)
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    records = [shot_record(p, s) for s in p.shots]

    # 1. Machine-readable prompts (one per shot + an index) and plain-text copies
    for r in records:
        (PROMPTS_DIR / f"{r['key']}.json").write_text(json.dumps(r, indent=2, ensure_ascii=False) + "\n")
    with open(PROMPTS_DIR / "ALL_PROMPTS.md", "w", encoding="utf-8") as f:
        f.write(f"# {p.config['project']['title']} — AI video prompts (Veo 3.1)\n\n")
        f.write("Generated by `make build` from `bible/` and `shots/shotlist.yaml`. "
                "Do not edit by hand.\n\n")
        f.write(f"**Negative prompt (every shot):** {_clean(p.style['negative_prompt'])}\n\n")
        for r in records:
            f.write(f"## Shot {r['id']:03d} · Ch {r['chapter']} · {r['timecode_in']}–{r['timecode_out']}"
                    f" · {r['duration']}s (generate {r['generate_seconds']}s)\n\n")
            f.write(f"Reference images: {', '.join(r['reference_images']) or '—'}\n\n")
            f.write("**Base (8 s):**\n\n```text\n" + r["base_prompt"] + "\n```\n\n")
            if r["extension_prompt"]:
                f.write("**Extension (+7 s):**\n\n```text\n" + r["extension_prompt"] + "\n```\n\n")

    # 2. Shot list CSV + Markdown
    with open(DOCS_DIR / "shotlist.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["shot", "chapter", "tc_in", "tc_out", "duration_s", "generate_s",
                    "location", "characters", "camera", "action", "action_ext",
                    "dialogue", "sfx", "music_cue"])
        for s, r in zip(p.shots, records):
            w.writerow([s.id, s.chapter, r["timecode_in"], r["timecode_out"], s.duration,
                        r["generate_seconds"], s.location, " ".join(s.characters),
                        _clean(s.camera), _clean(s.action), _clean(s.action_ext),
                        " | ".join(f"{_speaker(p, d.who)}: {d.line}" for d in s.dialogue),
                        "; ".join(s.sfx), r["music_cue"]])

    with open(DOCS_DIR / "shotlist.md", "w", encoding="utf-8") as f:
        f.write(f"# Shot list — {p.config['project']['title']}\n\n")
        f.write(f"{len(p.shots)} shots · running time {fmt_tc(p.total)} · "
                f"{sum(p.gen_seconds(s) for s in p.shots)} s to generate\n\n")
        cur = None
        for s, r in zip(p.shots, records):
            if s.chapter != cur:
                cur = s.chapter
                f.write(f"\n## {p.chapters[cur]}\n\n| # | TC in | Dur | Location | Who | Action |\n"
                        "|---|---|---|---|---|---|\n")
            act = _clean(s.action) + (f" ⟶ {_clean(s.action_ext)}" if s.extended else "")
            who = ", ".join(_speaker(p, c) for c in s.characters) or "—"
            f.write(f"| {s.id:03d} | {r['timecode_in']} | {s.duration}s | {s.location} | {who} | {act} |\n")

    # 3. Dialogue script (screenplay-style) — also the TTS/voice-actor fallback script
    with open(DOCS_DIR / "dialogue_script.md", "w", encoding="utf-8") as f:
        f.write(f"# Dialogue script — {p.config['project']['title']}\n\n")
        f.write("Every spoken line, in order, with timecodes. Veo generates these lines "
                "in-clip (lip-synced). For re-voicing, record/TTS each line to "
                "`audio/dialogue/shot_###.wav` and it will be mixed over the clip.\n\n")
        f.write("## Voice sheet\n\n| Character | Voice |\n|---|---|\n")
        for k, c in p.characters.items():
            f.write(f"| {c['name']} | {_clean(c['voice'])} |\n")
        cur = None
        n = 0
        for s in p.shots:
            if s.chapter != cur:
                cur = s.chapter
                f.write(f"\n## {p.chapters[cur]}\n")
            if not s.dialogue:
                continue
            f.write(f"\n**SHOT {s.id:03d}** — {fmt_tc(s.start)} — {s.location}\n\n")
            for d in s.dialogue:
                n += 1
                seg = " *(extension)*" if d.ext else ""
                deliv = f" *({d.delivery})*" if d.delivery else ""
                f.write(f"- **{_speaker(p, d.who).upper()}**{deliv}{seg}: {d.line}\n")
        f.write(f"\n---\n{n} lines total.\n")

    # 4. SFX cue sheet
    with open(DOCS_DIR / "sfx_cue_sheet.md", "w", encoding="utf-8") as f:
        f.write("# Sound-effects cue sheet\n\nVeo generates these in-clip. Use this list to "
                "spot-check each clip and to source library replacements; put any "
                "replacement/sweetener at `audio/sfx/shot_###.wav` (it is layered on top).\n\n"
                "| Shot | TC | Location ambience | Effects |\n|---|---|---|---|\n")
        for s in p.shots:
            f.write(f"| {s.id:03d} | {fmt_tc(s.start)} | {_clean(p.locations[s.location]['ambience'])} "
                    f"| {'; '.join(s.sfx) or '—'} |\n")

    # 5. Music cue sheet
    with open(DOCS_DIR / "music_cue_sheet.md", "w", encoding="utf-8") as f:
        f.write("# Music cue sheet\n\n" + _clean(p.music["theme"]) + "\n\n")
        f.write("| Cue | Title | Shots | In | Out | Length | Brief / generation prompt |\n"
                "|---|---|---|---|---|---|---|\n")
        for c in p.music["cues"]:
            a, b = p.cue_span(c)
            f.write(f"| {c['id']} | {c['title']} | {c['shots'][0]:03d}–{c['shots'][1]:03d} | "
                    f"{fmt_tc(a)} | {fmt_tc(b)} | {b - a:.0f}s | {_clean(c['prompt'])} |\n")
        f.write("\nDeliver each cue as `audio/music/<Cue>.wav` (e.g. `audio/music/M01.wav`).\n")

    # 6. Cost estimate
    gen = sum(p.gen_seconds(s) for s in p.shots)
    n_ext = sum(1 for s in p.shots if s.extended)
    with open(DOCS_DIR / "cost_estimate.md", "w", encoding="utf-8") as f:
        f.write("# Video-generation cost estimate (Google Veo 3.1, Gemini API)\n\n")
        f.write(f"Prices: {p.config['veo']['pricing_checked']}. Edit `pipeline/config.yaml` "
                "once you have checked the official pricing page.\n\n")
        f.write(f"- Shots: {len(p.shots)} ({len(p.shots) - n_ext} × 8 s base, "
                f"{n_ext} × 8 s base + 7 s extension)\n")
        f.write(f"- Seconds to generate per complete pass: **{gen} s** "
                f"(final cut uses {p.total:.0f} s)\n")
        f.write("- AI video rarely nails every shot first time; budget for retakes. "
                "The ×2.5 column assumes an average of 2.5 takes per shot.\n\n")
        f.write("| Tier | Resolution | One pass | With retakes (×2.5) |\n|---|---|---|---|\n")
        for tier, res, one, _ in cost_table(p):
            f.write(f"| {tier} | {res} | ${one:,.0f} | ${one * 2.5:,.0f} |\n")
        f.write("\nNotes: extension only works at 720p and not on Lite, so the pipeline renders "
                "720p and upscales to 1080p at assembly. Character reference sheets "
                f"(~{len(p.characters) + len(p.props)} images) cost a few dollars at most.\n")
