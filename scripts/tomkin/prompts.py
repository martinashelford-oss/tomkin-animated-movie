"""Compose Veo prompts and write the production documents."""
from __future__ import annotations

import csv
import json

from .project import ROOT, Project, Shot, clean, fmt_tc

PROMPTS = ROOT / "prompts"
DOCS = ROOT / "docs" / "generated"


def _cast(p: Project, s: Shot) -> str:
    return "; ".join(clean(p.chars[c]["look"]) for c in s.who)


def _dialogue(p: Project, s: Shot) -> str:
    if not s.lines:
        return "No dialogue."
    out = []
    for ln in s.lines:
        c = p.chars[ln.who]
        extra = f", {ln.delivery}" if ln.delivery else ""
        out.append(f'{c["name"][0].upper() + c["name"][1:]} ({clean(c["voice"])}{extra}) says: "{ln.text}"')
    return "Dialogue: " + " ".join(out)


def ref_keys(p: Project, s: Shot) -> list[str]:
    if "refs" in s.det:
        return s.det["refs"]
    order = ["tomkin", "penny", "hero", "leviathan2", "leviathan", "drone", "scouts", "swarm", "boat"]
    keys = sorted(s.who, key=lambda k: order.index(k) if k in order else 99)
    return keys[: p.config["veo"]["max_reference_images"]]


def base_prompt(p: Project, s: Shot) -> str:
    c = p.cont
    parts = [clean(c["style"]) + ".",
             f"Setting: {clean(c['locations'][s.at])}. Time and weather: {clean(c['times'][s.time])}."]
    if s.who:
        parts.append(f"Characters (keep exactly on-model): {_cast(p, s)}.")
    parts += [f"Camera: {clean(s.cam)}; one continuous shot, no cuts.",
              f"Action: {clean(s.base)}",
              _dialogue(p, s),
              f"Sound: {clean(s.sfx)}.",
              clean(c["audio_rule"])]
    return "\n".join(parts)


def ext_prompt(p: Project, s: Shot) -> str:
    names = ", ".join(p.chars[c]["name"] for c in s.who) or "the scene"
    return "\n".join([
        f"Continue this exact shot seamlessly with the same camera move, the same characters "
        f"({names}), identical costumes and props, the same setting, lighting and weather.",
        f"Action: {clean(s.ext)}",
        "No dialogue.",
        f"Sound continues: {clean(s.sfx)}.",
        clean(p.cont["audio_rule"])])


def record(p: Project, s: Shot) -> dict:
    cue = p.cue_for(s)
    return {"id": s.id, "title": s.title, "timecode": f"{fmt_tc(s.start)}–{fmt_tc(s.start + s.duration)}",
            "duration": s.duration, "generate_seconds": p.gen_seconds(s),
            "reference_images": [f"assets/refs/{k}.png" for k in ref_keys(p, s)],
            "base_prompt": base_prompt(p, s), "extension_prompt": ext_prompt(p, s),
            "negative_prompt": clean(p.cont["negative_prompt"]),
            "dialogue": [f"{l.tag}: {l.text}" for l in s.lines],
            "music_cue": cue["id"] if cue else None, "overlay": s.overlay}


def write_all(p: Project) -> None:
    PROMPTS.mkdir(exist_ok=True)
    DOCS.mkdir(parents=True, exist_ok=True)
    recs = [record(p, s) for s in p.shots]
    for r in recs:
        (PROMPTS / f"{r['id']}.json").write_text(json.dumps(r, indent=2, ensure_ascii=False) + "\n")
    v = p.config["veo"]
    with open(PROMPTS / "ALL_PROMPTS.md", "w", encoding="utf-8") as f:
        f.write(f"# {p.config['project']['title']}: Veo 3.1 prompts for all 90 shots\n\n"
                "Generated by `python scripts/build_prompts.py` from `shots.json` and `production/`. "
                "Do not edit by hand. Each shot is generated as an 8 s base clip plus a 7 s "
                "extension, then trimmed to 10 s at assembly.\n\n"
                f"**Negative prompt (all shots):** {clean(p.cont['negative_prompt'])}\n\n")
        for s, r in zip(p.shots, recs):
            f.write(f"## {s.id} · {s.title} · {r['timecode']}\n\n"
                    f"*shots.json action:* {s.action}  \n"
                    f"*Reference images:* {', '.join(r['reference_images']) or 'none'}\n\n"
                    f"**Base, 8 s**\n\n```text\n{r['base_prompt']}\n```\n\n"
                    f"**Extension, +7 s (seconds 8–10 kept)**\n\n```text\n{r['extension_prompt']}\n```\n\n")

    with open(DOCS / "shot_list.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["id", "timecode", "title", "action", "characters", "location", "time",
                    "camera", "dialogue", "sfx", "music_cue"])
        for s, r in zip(p.shots, recs):
            w.writerow([s.id, r["timecode"], s.title, s.action, " ".join(s.who), s.at, s.time,
                        clean(s.cam), " | ".join(r["dialogue"]), clean(s.sfx), r["music_cue"]])

    with open(DOCS / "dialogue_script.md", "w", encoding="utf-8") as f:
        f.write("# Dialogue script\n\nAll spoken lines from `shots.json`. By default Veo performs them "
                "in-clip with lip-sync. To use supplied voices instead, record each shot's lines to "
                "`assets/audio/voice_###.wav` (e.g. `voice_001.wav`). The file is mixed over that shot "
                "from its first frame, so leave any lead-in silence in the recording.\n\n"
                "## Voice sheet\n\n| Role | Voice direction |\n|---|---|\n")
        for k in ("tomkin", "penny", "hero", "boat"):
            f.write(f"| {p.chars[k]['name']} | {clean(p.chars[k]['voice'])} |\n")
        f.write("\n## Lines\n\n| Shot | Timecode | Speaker | Line | Delivery | Voice file |\n|---|---|---|---|---|---|\n")
        n = 0
        for s in p.shots:
            for ln in s.lines:
                n += 1
                f.write(f"| {s.id} | {fmt_tc(s.start)} | {ln.tag} | {ln.text} | {ln.delivery} | voice_{s.id}.wav |\n")
        f.write(f"\n{n} lines in {sum(1 for s in p.shots if s.lines)} shots.\n")

    with open(DOCS / "sound_design.md", "w", encoding="utf-8") as f:
        f.write("# Sound-design cue sheet\n\nVeo generates these sounds in-clip. Use this sheet to "
                "review each clip, and add sweeteners or replacements as `assets/audio/sfx_###.wav`, "
                "which is mixed over the shot.\n\n| Shot | Timecode | Title | Effects |\n|---|---|---|---|\n")
        for s in p.shots:
            f.write(f"| {s.id} | {fmt_tc(s.start)} | {s.title} | {clean(s.sfx)} |\n")

    with open(DOCS / "music_cue_sheet.md", "w", encoding="utf-8") as f:
        f.write(f"# Music cue sheet\n\n{clean(p.music['theme'])}\n\nOriginal or properly licensed "
                "music only. Deliver either one full-length `assets/audio/music.mp3` or the cues below "
                "as `assets/audio/music/M01.wav` and so on.\n\n"
                "| Cue | Title | Shots | In | Out | Length | Brief |\n|---|---|---|---|---|---|---|\n")
        for c in p.music["cues"]:
            a, b = p.cue_span(c)
            f.write(f"| {c['id']} | {c['title']} | {c['shots'][0]:03d}–{c['shots'][1]:03d} | {fmt_tc(a)} | "
                    f"{fmt_tc(b)} | {b - a:.0f}s | {c['prompt']} |\n")

    gen = sum(p.gen_seconds(s) for s in p.shots)
    with open(DOCS / "cost_estimate.md", "w", encoding="utf-8") as f:
        f.write(f"# Veo 3.1 cost estimate\n\nPricing: {v['pricing_checked']}.\n\n"
                f"- 90 shots × (8 s base + 7 s extension) = **{gen} generated seconds** per full pass "
                f"(the cut uses {p.total:.0f} s).\n"
                "- Plan on about 2.5 takes per shot on average to cover retakes for continuity "
                "errors.\n\n| Tier (720p) | $/s | One pass | ×2.5 takes |\n|---|---|---|---|\n")
        for tier, price in v["price_per_second"].items():
            f.write(f"| {tier} | {price:.2f} | ${gen * price:,.0f} | ${gen * price * 2.5:,.0f} |\n")
        f.write(f"\nReference sheets: ~{len(p.chars)} images × ~${p.config['images']['est_usd_per_image']} each.\n")
