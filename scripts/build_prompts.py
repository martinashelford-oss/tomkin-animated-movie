#!/usr/bin/env python3
"""Build every production document from shots.json + production/bible.json.

Outputs (production/generated/):
  video_prompts.md     human-readable prompt book for all 90 shots
  video_jobs.jsonl     one machine-readable generation job per shot (service-agnostic)
  dialogue_script.md   screenplay-style dialogue script with timecodes
  voice_lines.csv      one row per line for voice recording / TTS
  sfx_cue_sheet.csv    sound-effect cues per shot
  music_cue_sheet.md   composer brief / cue sheet
  reference_sheets.md  prompts for the character/prop reference images
Also creates production/shot_tracker.csv once (never overwritten).

Usage: python scripts/build_prompts.py [--max-chars 2500]
"""
from __future__ import annotations

import argparse
import csv
import json

from common import (GENERATED, ROOT, all_dialogue, load_bible, load_cues, load_shots,
                    parse_dialogue_line)

SPEAKER_TO_CODE = {"TOMKIN": "T", "PENNY": "P", "HERO": "H"}


def tc(seconds: float) -> str:
    m, s = divmod(int(round(seconds)), 60)
    return f"{m:02d}:{s:02d}"


def compose_prompt(shot, bible) -> str:
    chars = bible["characters"]
    loc = bible["locations"][shot["location"]]
    light = bible["phases"][shot["lighting_phase"]]
    parts = [shot["prompt_body"].strip()]
    if shot["characters"]:
        parts.append("Character designs (keep exactly consistent): " +
                     "; ".join(chars[c]["block"] for c in shot["characters"]) + ".")
    speakers = []
    for line, _src in all_dialogue(shot):
        spk, _, _ = parse_dialogue_line(line)
        code = SPEAKER_TO_CODE.get(spk or "")
        if code and code in shot["characters"] and chars[code]["name"] not in speakers:
            speakers.append(chars[code]["name"])
    if speakers:
        parts.append(f"{', '.join(speakers)} speak{'s' if len(speakers) == 1 else ''} in this shot "
                     "with natural mouth movement (voices are added later).")
    parts.append(f"Setting: {loc}.")
    parts.append(f"Lighting: {light}.")
    parts.append(f"{bible['style']}. {bible['camera_rule']}.")
    return " ".join(parts)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--max-chars", type=int, default=2500,
                    help="warn when a prompt exceeds this length (Kling's prompt limit is 2500)")
    args = ap.parse_args()

    shots, bible, cues = load_shots(), load_bible(), load_cues()
    GENERATED.mkdir(parents=True, exist_ok=True)
    chars = bible["characters"]

    # ---- video prompts + jobs -------------------------------------------------
    jobs, md, long_prompts = [], ["# Video prompt book: Tomkin and the Lighthouse Leviathan",
                                  "", "Generated by `scripts/build_prompts.py` — edit `shots.json` / "
                                  "`production/bible.json`, not this file.", "",
                                  f"**Negative prompt (all shots):** {bible['negative_prompt']}", ""], []
    for s in shots:
        prompt = compose_prompt(s, bible)
        if len(prompt) > args.max_chars:
            long_prompts.append((s["id"], len(prompt)))
        refs = sorted({chars[c]["reference_image"] for c in s["characters"]})
        jobs.append({
            "id": s["id"], "title": s["title"], "duration_seconds": s["duration_seconds"],
            "aspect_ratio": "16:9", "target_resolution": "1920x1080", "fps": 24, "audio": False,
            "prompt": prompt, "negative_prompt": bible["negative_prompt"],
            "reference_images": refs,
            "continuity_from_previous": f"assets/video/{int(s['id']) - 1:03d}.mp4" if int(s["id"]) > 1 else None,
            "output_path": f"assets/video/{s['id']}.mp4",
        })
        md += [f"## {s['id']} · {s['title']}  `{tc(s['start_seconds'])}–{tc(s['start_seconds'] + s['duration_seconds'])}`",
               "", f"*Story beat:* {s['action']}", ""]
        if s.get("continuity_note"):
            md += [f"*Continuity:* {s['continuity_note']}", ""]
        md += [f"*References:* {', '.join(refs) or '—'} · *Prompt length:* {len(prompt)} chars", "",
               "```text", prompt, "```", ""]
    (GENERATED / "video_prompts.md").write_text("\n".join(md), encoding="utf-8")
    with open(GENERATED / "video_jobs.jsonl", "w", encoding="utf-8") as fh:
        for j in jobs:
            fh.write(json.dumps(j, ensure_ascii=False) + "\n")

    # ---- dialogue -------------------------------------------------------------
    script = ["# Dialogue script: Tomkin and the Lighthouse Leviathan", "",
              "Lines marked **[ORIGINAL]** come from the supplied `shots.json` and must be kept. "
              "Lines marked *[proposed]* are new suggestions for review; delete or edit them in "
              "`shots.json` → `dialogue_proposed`.", "",
              "Each shot is 10 seconds; keep the lines in a shot under about 25 words in total.", ""]
    rows = []
    for s in shots:
        lines = all_dialogue(s)
        if not lines:
            continue
        script.append(f"### {s['id']} · {s['title']} ({tc(s['start_seconds'])})")
        script.append(f"_{s['action']}_")
        script.append("")
        for n, (line, src) in enumerate(lines, 1):
            spk, text, direction = parse_dialogue_line(line)
            tag = "**[ORIGINAL]**" if src == "original" else "*[proposed]*"
            dtxt = f" *({direction})*" if direction else ""
            script.append(f"- {tag} **{spk}**{dtxt}: {text}")
            rows.append({"shot": s["id"], "line": f"{n:02d}", "speaker": spk, "text": text,
                         "direction": direction, "source": src,
                         "shot_start_seconds": s["start_seconds"], "offset_seconds": "",
                         "file": f"assets/audio/voice/{s['id']}_{n:02d}.wav"})
        script.append("")
    words = sum(len(r["text"].split()) for r in rows)
    script += ["---", f"Total lines: {len(rows)} ({sum(r['source'] == 'original' for r in rows)} original, "
               f"{sum(r['source'] == 'proposed' for r in rows)} proposed), about {words} words."]
    (GENERATED / "dialogue_script.md").write_text("\n".join(script) + "\n", encoding="utf-8")
    with open(GENERATED / "voice_lines.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    # ---- SFX ------------------------------------------------------------------
    with open(GENERATED / "sfx_cue_sheet.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["shot", "timecode", "title", "ambience_bed", "sfx_cues", "original_sound_design_note",
                    "stem_file"])
        for s in shots:
            w.writerow([s["id"], tc(s["start_seconds"]), s["title"], s["lighting_phase"],
                        "; ".join(s["sfx_cues"]), s["sound_design"], f"assets/audio/sfx/{s['id']}.wav"])

    # ---- Music ----------------------------------------------------------------
    by_id = {s["id"]: s for s in shots}
    mus = ["# Music cue sheet / composer brief", "",
           "Original or properly licensed music only. Deliver each cue as "
           "`assets/audio/music/<CUE>.wav` (48 kHz stereo) cut to the length below, or one "
           "continuous score as `assets/audio/music.mp3` (or .wav).", "",
           "**Themes:** *Tomkin's theme* (pompous, playful march, clarinet/brass), *Penny's motif* "
           "(three rising notes, solo trumpet or oboe), *Hero motif* (horns, leaping fifths), "
           "*Leviathan theme* (low brass and choir, chromatic).", "",
           "| Cue | Shots | Start | Length | Title | Tempo / key | Mood |", "|---|---|---|---|---|---|---|"]
    for c in cues:
        a, b = by_id[c["first_shot"]], by_id[c["last_shot"]]
        start, end = a["start_seconds"], b["start_seconds"] + b["duration_seconds"]
        c["_start"], c["_len"] = start, end - start
        mus.append(f"| {c['cue']} | {c['first_shot']}–{c['last_shot']} | {tc(start)} | {end - start}s | "
                   f"{c['title']} | {c['tempo_bpm']} bpm, {c['key']} | {c['mood']} |")
    mus.append("")
    for c in cues:
        mus += [f"## {c['cue']} · {c['title']} ({tc(c['_start'])}, {c['_len']}s)",
                f"- **Instrumentation:** {c['instrumentation']}",
                f"- **Sync points:** {'; '.join(c['sync_points']) or '—'}",
                f"- **Ending:** {c['end']}",
                f"- **Text prompt (for a licensed AI music tool):** \"Orchestral film score cue, {c['mood']}, "
                f"{c['tempo_bpm']} bpm, {c['key']}, {c['instrumentation']}, family adventure animation, "
                f"instrumental, no vocals, {c['_len']} seconds\"", ""]
    (GENERATED / "music_cue_sheet.md").write_text("\n".join(mus), encoding="utf-8")

    # ---- Reference sheets -----------------------------------------------------
    ref = ["# Reference image prompts", "",
           "Create these first (text-to-image or a 3D artist), approve them, and save them to the "
           "listed paths. Every video job attaches the references for the characters in that shot.", ""]
    seen = set()
    for code, c in chars.items():
        if c["reference_image"] in seen:
            continue
        seen.add(c["reference_image"])
        ref += [f"## {c['name']} → `{c['reference_image']}`", "", "```text",
                f"Character turnaround reference sheet, front, three-quarter, side and back views plus "
                f"three facial expressions, neutral grey studio background, even soft lighting, "
                f"stylized-realistic 3D CGI animated feature-film quality. {c['block']}. No text labels.",
                "```", ""]
    ref += ["## Lighthouse → `assets/reference/lighthouse.png`", "", "```text",
            "Environment concept sheet, establishing exterior, gallery catwalk close-up and lantern-room "
            f"interior, stylized-realistic 3D CGI. {bible['locations']['gallery']}; "
            f"{bible['locations']['lantern_room']}; {bible['locations']['tower_exterior']}. No text.",
            "```", ""]
    (GENERATED / "reference_sheets.md").write_text("\n".join(ref), encoding="utf-8")

    # ---- Tracker (create once) -----------------------------------------------
    tracker = ROOT / "production" / "shot_tracker.csv"
    if not tracker.exists():
        with open(tracker, "w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh)
            w.writerow(["shot", "title", "status", "takes", "chosen_take", "service", "cost_usd", "notes"])
            for s in shots:
                w.writerow([s["id"], s["title"], "not_generated", 0, "", "", "", ""])

    print(f"Wrote {len(jobs)} prompts, {len(rows)} dialogue lines, {len(cues)} music cues to "
          f"{GENERATED.relative_to(ROOT)}/")
    lens = [len(j["prompt"]) for j in jobs]
    print(f"Prompt length: min {min(lens)}, max {max(lens)} chars")
    if long_prompts:
        print(f"WARNING: {len(long_prompts)} prompts exceed {args.max_chars} chars: "
              + ", ".join(f"{i}({n})" for i, n in long_prompts))


if __name__ == "__main__":
    main()
